def get_account_goal_profile_by_slug(goal_slug: str) -> dict | None:
    """Return an isolated profile by canonical builder goal slug."""
    normalized_goal_slug = str(goal_slug or "").strip().lower()
    profile = _ACCOUNT_GOAL_PROFILES_BY_SLUG.get(normalized_goal_slug)

    if profile is None:
        return None

    category_value = next(
        (
            candidate_category_value
            for candidate_category_value, candidate_profile in (
                ACCOUNT_GOAL_RECIPE_PROFILES.items()
            )
            if candidate_profile["goal_slug"] == normalized_goal_slug
        ),
        None,
    )

    if category_value is None:
        raise RuntimeError(
            "Account health-goal profile has no category mapping: "
            f"{normalized_goal_slug!r}"
        )

    result = deepcopy(profile)
    result["category_value"] = category_value
    return result


def get_account_goal_profile_slugs() -> tuple[str, ...]:
    """Return canonical goal slugs supported by account-goal profiles."""
    return tuple(sorted(_ACCOUNT_GOAL_PROFILES_BY_SLUG))


